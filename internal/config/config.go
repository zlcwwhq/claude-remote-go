// Package config loads claude-remote's settings and knows where its state
// lives on disk.
//
// The config file keeps the shell-assignment format of the original bash
// implementation's config.sh (KEY="value" lines), so an existing config.sh can
// be copied over unchanged. It is parsed, never executed.
package config

import (
	"errors"
	"fmt"
	"io/fs"
	"os"
	"path/filepath"
	"strings"
)

// DefaultMirrorRoot is offered by setup when no mirror root is given.
const DefaultMirrorRoot = "/home/ubuntu/claude-remote-mirror"

// ErrNotFound is returned by Load when the config file does not exist.
var ErrNotFound = errors.New("config not found")

// Config holds the user's settings.
type Config struct {
	// Path is the file the values were read from.
	Path string

	// RemoteHost is the ssh destination (user@host or an ~/.ssh/config alias).
	RemoteHost string
	// MirrorRoot is the directory on the remote that mirrors local absolute
	// paths (local /abs/path -> MirrorRoot/abs/path). Unused with PathIdentity.
	MirrorRoot string
	// PathIdentity syncs to the identical absolute path on the remote.
	PathIdentity bool
	// ModeSeed is CLAUDE_REMOTE_MODE: the lowest-priority mode input.
	ModeSeed string
	// ImageCache is REMOTE_IMAGE_CACHE, where paste-image-remote uploads to.
	ImageCache string
}

// StateDir is where mode/url/session files live
// ($CLAUDE_REMOTE_STATE_DIR, default ~/.claude-remote).
func StateDir() string {
	if d := os.Getenv("CLAUDE_REMOTE_STATE_DIR"); d != "" {
		return d
	}
	home, err := os.UserHomeDir()
	if err != nil {
		return ".claude-remote"
	}
	return filepath.Join(home, ".claude-remote")
}

// FilePath is the config file location
// ($CLAUDE_REMOTE_CONFIG, default <state dir>/config.sh).
func FilePath() string {
	if p := os.Getenv("CLAUDE_REMOTE_CONFIG"); p != "" {
		return p
	}
	return filepath.Join(StateDir(), "config.sh")
}

// Load reads and parses the config file.
func Load() (*Config, error) {
	path := FilePath()
	data, err := os.ReadFile(path)
	if errors.Is(err, fs.ErrNotExist) {
		return nil, fmt.Errorf("%w at %s. Run 'claude-remote setup' first", ErrNotFound, path)
	}
	if err != nil {
		return nil, err
	}
	vals, err := Parse(data, os.Getenv)
	if err != nil {
		return nil, fmt.Errorf("%s: %w", path, err)
	}
	c := FromValues(vals, os.Getenv)
	c.Path = path
	return c, nil
}

// FromValues builds a Config from parsed assignments. As with the sourced
// config.sh, a value set in the file wins; CLAUDE_REMOTE_MODE and
// REMOTE_IMAGE_CACHE fall back to the environment when the file leaves them out.
func FromValues(vals map[string]string, getenv func(string) string) *Config {
	fileOrEnv := func(key string) string {
		if v, ok := vals[key]; ok {
			return v
		}
		return getenv(key)
	}
	return &Config{
		RemoteHost:   vals["REMOTE_HOST"],
		MirrorRoot:   vals["REMOTE_MIRROR_ROOT"],
		PathIdentity: vals["PATH_IDENTITY"] == "true",
		ModeSeed:     fileOrEnv("CLAUDE_REMOTE_MODE"),
		ImageCache:   fileOrEnv("REMOTE_IMAGE_CACHE"),
	}
}

// Validate reports settings the remote path mapping cannot work without.
func (c *Config) Validate() error {
	if !c.PathIdentity && c.MirrorRoot == "" {
		return fmt.Errorf("REMOTE_MIRROR_ROOT not set in %s", c.Path)
	}
	return nil
}

func (c *Config) mirrorRoot() string {
	return strings.TrimRight(c.MirrorRoot, "/")
}

// LocalToRemote maps a local absolute path to its location on the remote.
func (c *Config) LocalToRemote(p string) string {
	if c.PathIdentity {
		return p
	}
	return c.mirrorRoot() + p
}

// RemoteToLocal maps a remote absolute path back to the local path it
// mirrors. Paths outside the mirror root are returned unchanged.
func (c *Config) RemoteToLocal(p string) string {
	root := c.mirrorRoot()
	if c.PathIdentity || root == "" {
		return p
	}
	if p == root {
		return "/"
	}
	if strings.HasPrefix(p, root+"/") {
		return p[len(root):]
	}
	return p
}

// Write saves c to path in the config.sh format, creating parent directories.
func Write(path string, c *Config) error {
	identity := "false"
	if c.PathIdentity {
		identity = "true"
	}
	content := fmt.Sprintf(`# Claude Remote Configuration
# Generated by 'claude-remote setup'

REMOTE_HOST=%s
REMOTE_MIRROR_ROOT=%s

# PATH_IDENTITY: when true, sync to the identical absolute path on the box.
# When false (default/legacy), paths are mirrored under REMOTE_MIRROR_ROOT.
PATH_IDENTITY=%s
`, quote(c.RemoteHost), quote(c.MirrorRoot), quote(identity))
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	return os.WriteFile(path, []byte(content), 0o644)
}

// quote double-quotes s so Parse (and a shell) reads it back verbatim.
func quote(s string) string {
	r := strings.NewReplacer(`\`, `\\`, `"`, `\"`, `$`, `\$`, "`", "\\`")
	return `"` + r.Replace(s) + `"`
}
